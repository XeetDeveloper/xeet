/* Regenerates dev/popup-preview.html from the real popup.
 *
 * The popup is an extension page: it talks to a service worker that a plain
 * tab does not have. Rather than keep a second copy of its markup in sync by
 * hand, this rewrites the shipped file's paths and slips the harness shim and
 * the real background script in ahead of popup.js. Run it after touching the
 * popup:  node dev/make-popup-preview.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../popup/popup.html", import.meta.url), "utf8");
// The popup compares its own version against the worker's. Without the real
// number here the harness always looks stale, which would hide the very thing
// the check exists to catch.
const { version } = JSON.parse(readFileSync(new URL("../manifest.json", import.meta.url), "utf8"));
const out = src
  .replace(/(href|src)="\.\.\//g, '$1="../')          // ../assets → still ../assets from dev/
  .replace(/href="popup\.css"/, 'href="../popup/popup.css"')
  .replace(/<script src="popup\.js"><\/script>/,
    `<script>window.__XEET_MANIFEST_VERSION = ${JSON.stringify(version)};</script>\n`
    + '<script src="shim.js"></script>\n<script type="module" src="../src/background.js"></script>\n<script src="../popup/popup.js"></script>')
  .replace(/<title>[^<]*<\/title>/, "<title>Xeet — popup harness</title>");

writeFileSync(new URL("popup-preview.html", import.meta.url),
  "<!-- GENERATED by dev/make-popup-preview.mjs. Do not edit. -->\n" + out);
console.log("wrote dev/popup-preview.html");
