  /* -------------------------------------------------------------- the flock */
  // Chain marks (the product's vendored SVGs) that orbit the fee, then fly
  // into the rail. The first five become token faces on arrival.
  const CHAIN_ORDER = ["solana", "ethereum", "robinhood", "base", "bsc", "polygon", "optimism"];
  // The rail's rows, top to bottom, in the shape the popup's board draws them:
